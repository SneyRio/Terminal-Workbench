// Working / waiting status for agents other than Claude Code. Each CLI reports turn starts and ends
// through its own mechanism; all of them end up writing the same event file the Claude hooks write.
const fs=require('node:fs/promises');
const path=require('node:path');
const {spawn}=require('node:child_process');
const {pathToFileURL}=require('node:url');
const platform=require('./platform.cjs');

// The hook command runs the bundled telemetry script with the app's own runtime. It stays the same for
// every session, so Codex trust recorded once keeps matching; the session comes from the environment.
function eventCommand(runtime,script,os=process.platform){
 if(os==='win32')return `set "ELECTRON_RUN_AS_NODE=1"&& "${runtime}" "${script}" event`;
 return `/usr/bin/env ELECTRON_RUN_AS_NODE=1 ${platform.quotePosix(runtime)} ${platform.quotePosix(script)} event`;
}

// Qoder follows Claude Code's hook format and events, including StopFailure for turns ending on an API error.
const QODER_EVENTS=['SessionStart','UserPromptSubmit','Stop','StopFailure','SessionEnd'];
function qoderHooks(runtime,script,os=process.platform){
 const command=os==='win32'?platform.powershellCommand("$env:ELECTRON_RUN_AS_NODE = '1'; $input | Out-String | & "+platform.quotePowerShell(runtime.replaceAll('\\','/'))+' '+platform.quotePowerShell(script)+' event'):eventCommand(runtime,script,os);
 return Object.fromEntries(QODER_EVENTS.map(event=>[event,[{hooks:[{type:'command',command}]}]]));
}

// Codex: hooks are passed as session flags. It has no failure event; Interrupt covers Esc.
const CODEX_EVENTS=['SessionStart','UserPromptSubmit','Stop','Interrupt'];
// Codex caps Interrupt hooks at 3 seconds and warns in its UI when asked for more.
const codexHookArgs=command=>CODEX_EVENTS.flatMap(event=>['-c',`hooks.${event}=[{hooks=[{type="command",command=${JSON.stringify(command)},timeout=${event==='Interrupt'?3:10}}]}]`]);

// Codex runs a hook only once its hash is trusted in the user config, as when someone approves it in the Codex UI.
// Codex itself reports the key and hash through `hooks/list`, so nothing about its hashing is copied here.
function listCodexHooks(command,env,cwd,{spawner=spawn,timeoutMs=5000}={}){
 return new Promise(resolve=>{
  let buffer='',settled=false,child;
  const finish=value=>{if(settled)return;settled=true;clearTimeout(timer);try{child?.kill();}catch{}resolve(value);};
  const timer=setTimeout(()=>finish(null),timeoutMs);
  try{child=spawner(command[0],command[1],{env,cwd,windowsHide:true,stdio:['pipe','pipe','ignore']});}catch{finish(null);return;}
  child.on('error',()=>finish(null));child.on('close',()=>finish(null));child.stdin.on('error',()=>{});
  const send=message=>{try{child.stdin.write(JSON.stringify(message)+'\n');}catch{finish(null);}};
  child.stdout.on('data',chunk=>{
   buffer+=chunk;if(buffer.length>4*1024*1024){finish(null);return;}
   let end;
   while((end=buffer.indexOf('\n'))>=0){
    const line=buffer.slice(0,end);buffer=buffer.slice(end+1);
    let message;try{message=JSON.parse(line);}catch{continue;}
    if(message.id===1){send({method:'initialized'});send({id:2,method:'hooks/list',params:{cwds:[cwd]}});}
    if(message.id===2)finish(message.result?.data?.flatMap(d=>d.hooks||[])||null);
   }
  });
  send({id:1,method:'initialize',params:{clientInfo:{name:'wbspace',title:'WbSpace',version:'1'}}});
 });
}
const ownCodexHooks=(hooks,command)=>(hooks||[]).filter(h=>h.source==='sessionFlags'&&h.command===command&&typeof h.key==='string'&&/^sha256:[0-9a-f]{64}$/.test(h.currentHash||'')).map(h=>({key:h.key,hash:h.currentHash}));

// Replaces WbSpace's trust tables (session-flag hooks only exist when WbSpace starts Codex) and keeps everything else.
const ownTrustHeader=line=>/^\s*\[hooks\.state\."[^"]*<session-flags>[^"]*"\]\s*$/.test(line);
function applyCodexTrust(text,entries){
 const kept=[];let skipping=false;
 for(const line of String(text||'').split('\n')){
  if(/^\s*\[/.test(line))skipping=ownTrustHeader(line);
  if(!skipping)kept.push(line);
 }
 const body=kept.join('\n').replace(/\s+$/,'');
 const blocks=entries.map(e=>`[hooks.state.${JSON.stringify(e.key)}]\ntrusted_hash = ${JSON.stringify(e.hash)}\n`);
 return (body?body+'\n\n':'')+blocks.join('\n');
}
async function writeCodexTrust(home,entries){
 const file=path.join(home,'config.toml');
 const current=await fs.readFile(file,'utf8').catch(error=>{if(error.code==='ENOENT')return '';throw error;});
 const next=applyCodexTrust(current,entries);
 if(next===current)return;
 await fs.mkdir(home,{recursive:true,mode:0o700});
 const tmp=file+'.'+process.pid+'.tmp';
 try{await fs.writeFile(tmp,next,{mode:0o600});await fs.rename(tmp,file);}finally{await fs.rm(tmp,{force:true});}
}

// OpenCode: a plugin follows session.status for the session and any sub-agent sessions it starts.
const OPENCODE_PLUGIN=`// Generated by WbSpace: reports whether this OpenCode session is working or waiting.
import fs from 'node:fs';
import path from 'node:path';
const dir=process.env.ACCOUNTOR_TELEMETRY_DIR,run=process.env.ACCOUNTOR_RUN_ID,busy=new Set();
let last='';
const write=event=>{
 if(!dir||!run||!/^[a-zA-Z0-9-]+$/.test(run)||event===last)return;last=event;
 try{const target=path.join(dir,run+'-event.json'),tmp=target+'.'+process.pid+'.tmp';fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(tmp,JSON.stringify({time:Date.now(),event}));fs.renameSync(tmp,target);}catch{}
};
export const WbSpaceStatus=async()=>{
 write('SessionStart');
 return {event:async({event})=>{
  const id=event?.properties?.sessionID;if(!id)return;
  if(event.type==='session.status'){if(event.properties.status?.type==='idle')busy.delete(id);else busy.add(id);}
  else if(event.type==='session.idle')busy.delete(id);
  else return;
  write(busy.size?'UserPromptSubmit':'Stop');
 }};
};
`;
async function opencodePlugin(dir){
 const file=path.join(dir,'opencode-status.js');
 const current=await fs.readFile(file,'utf8').catch(()=>null);
 if(current!==OPENCODE_PLUGIN){await fs.mkdir(dir,{recursive:true,mode:0o700});await fs.writeFile(file,OPENCODE_PLUGIN,{mode:0o600});}
 return pathToFileURL(file).href;
}
function mergeOpencodePlugin(current,url){
 let config={};try{config=current?JSON.parse(current):{};}catch{config={};}
 const plugin=[...(Array.isArray(config.plugin)?config.plugin:[]).filter(p=>p!==url),url];
 return JSON.stringify({$schema:'https://opencode.ai/config.json',...config,plugin});
}

// Fallback for turns that end without a hook: an agent at work keeps redrawing its spinner or timer, so a
// "working" session whose terminal has been silent this long is waiting for input (error before the request,
// Esc in Claude Code, a permission prompt). Scheduled runs print nothing while they work and are left alone.
const QUIET_MS=15000;
function quietSessions(sessions,terminals,now=Date.now(),quietMs=QUIET_MS){
 return sessions.filter(r=>{
  const t=terminals.get(r.id);
  return r.status==='busy'&&(r.kind==='claude'||r.kind==='agent')&&!r.scheduleRunId&&t&&!t.chat&&!t.closed&&now-(t.lastOutput||0)>=quietMs&&now-(r.eventTime||0)>=quietMs;
 }).map(r=>r.id);
}

