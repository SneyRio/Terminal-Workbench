import { _electron as electron } from 'playwright';
import { expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const testRoot=path.join(root,'.test-data','smoke-'+Date.now());
const project=path.join(testRoot,'project'), extra=path.join(testRoot,'extra');
await fs.mkdir(project,{recursive:true});await fs.mkdir(extra,{recursive:true});
await fs.writeFile(path.join(project,'README.md'),'# 工作空间测试\n\n真实文件编辑。\n');
await fs.writeFile(path.join(extra,'extra.json'),'{"project":"extra"}');
const reports=path.join(root,'test-results');await fs.mkdir(reports,{recursive:true});
const errors=[];const checks=[];
const app=await electron.launch({...(process.env.ACCOUNTOR_EXECUTABLE?{executablePath:process.env.ACCOUNTOR_EXECUTABLE,args:[]}:{args:[root]}),env:{...process.env,ACCOUNTOR_DATA_DIR:path.join(testRoot,'data'),ELECTRON_ENABLE_LOGGING:'1'}});
let page;
try{
  page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1024});
  await expect(page.getByRole('heading',{name:'你的工作空间'})).toBeVisible();checks.push('native preload and empty start');
  await app.evaluate(async({dialog},paths)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:paths});},[project,extra]);
  await page.getByRole('button',{name:'创建第一个工作空间'}).click();
  await page.getByRole('button',{name:'选择一个或多个本地项目'}).click();
  await expect(page.locator('.project-item')).toHaveCount(2);
  await page.getByPlaceholder('例如：业务研发').fill('账号工具研发');
  await page.getByRole('button',{name:'保存工作空间',exact:true}).click();
  await expect(page.getByRole('heading',{name:'账号工具研发',exact:true})).toBeVisible();checks.push('native multi-project workspace creation');
  await page.getByRole('button',{name:'打开 Shell',exact:true}).click();
  await expect(page.locator('.terminal-frame')).toBeVisible();
  const state=await page.evaluate(()=>window.accountor.invoke('state:get'));
  const session=state.sessions.at(-1);expect(session.cwd).toBe(project);
  await page.evaluate(async sid=>{await window.accountor.invoke('terminal:input',sid,"printf 'ACCOUNTOR_PTY_OK\\n'; pwd\r");},session.id);
  await expect.poll(()=>page.evaluate(sid=>window.accountor.invoke('terminal:buffer',sid),session.id)).toMatchObject({data:expect.stringContaining('ACCOUNTOR_PTY_OK')});checks.push('real PTY input/output and first-project cwd');
  await page.getByRole('button',{name:'展开右侧辅助栏',exact:true}).click();
  await expect(page.getByLabel('文件与编辑器')).toBeVisible();
  await page.getByRole('button',{name:'README.md',exact:true}).click();
  await expect(page.locator('.markdown-preview')).toContainText('工作空间测试');checks.push('real file tree and Markdown rendering');
  await page.getByRole('button',{name:'编辑',exact:true}).click();
  await page.locator('.cm-content').click();await page.keyboard.press('Meta+End');await page.keyboard.type('\n保存验证');
  await page.getByRole('button',{name:'保存文件',exact:true}).click();
  await expect.poll(()=>fs.readFile(path.join(project,'README.md'),'utf8')).toContain('保存验证');checks.push('CodeMirror edit and disk save');
  await page.locator('.cm-content').click();await page.keyboard.type('\n本地草稿');
  await fs.writeFile(path.join(project,'README.md'),'# 外部 CLI 修改\n');
  await expect(page.getByText('磁盘文件已变化',{exact:true})).toBeVisible({timeout:10000});checks.push('external CLI write conflict keeps editor draft');
  await page.locator('.cm-content').click();await page.keyboard.press('Meta+s');
  expect(await fs.readFile(path.join(project,'README.md'),'utf8')).toBe('# 外部 CLI 修改\n');checks.push('keyboard save cannot bypass unresolved conflict');
  await page.getByRole('button',{name:'关闭提示',exact:true}).click();
  await page.getByRole('button',{name:'收起右侧辅助栏',exact:true}).click();
  await expect(page.locator('.right-container')).toHaveClass(/collapsed/);
  await page.getByRole('button',{name:'展开右侧辅助栏',exact:true}).click();await expect(page.getByText('磁盘文件已变化',{exact:true})).toBeVisible();checks.push('collapsible right panel preserves editor state');
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await page.getByRole('button',{name:'黑夜',exact:true}).click();await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.getByLabel('不透明度数值').fill('50');await page.getByLabel('不透明度数值').press('Tab');
  await page.getByRole('button',{name:'浅灰',exact:true}).click();await expect(page.locator('html')).toHaveAttribute('data-theme','light');checks.push('theme switching and opacity settings');
  await page.getByRole('button',{name:'账号与连接',exact:false}).click();
  await page.locator('.connections-toolbar').getByRole('button',{name:'添加连接',exact:true}).click();await expect(page.getByRole('button',{name:'本机现有入口',exact:true})).toBeVisible();await expect(page.locator('.profile-buttons button')).toHaveCount(4);await page.getByRole('button',{name:'取消',exact:true}).click();checks.push('existing CLI profile discovery');
  await page.locator('.workspace-nav').filter({hasText:'账号工具研发'}).click();
  await expect(page.getByText('磁盘文件已变化',{exact:true})).toBeVisible();checks.push('navigation preserves unsaved file tabs');
  await page.screenshot({path:path.join(reports,'workspace-light.png')});
  await page.getByRole('button',{name:'会话选项',exact:true}).click();await page.getByRole('button',{name:'上下分屏 · Shell',exact:true}).click();
  await expect(page.locator('.terminal-slot.visible')).toHaveCount(2);checks.push('two live PTY panes');
  await page.screenshot({path:path.join(reports,'workspace-split.png')});
  const finalState=await page.evaluate(()=>window.accountor.invoke('state:get'));
  await fs.writeFile(path.join(reports,'smoke.json'),JSON.stringify({passed:true,packaged:!!process.env.ACCOUNTOR_EXECUTABLE,checks,errors,sessions:finalState.sessions.map(s=>({kind:s.kind,cwd:s.cwd,status:s.status})),testRoot},null,2));
  expect(errors).toEqual([]);
  console.log(JSON.stringify({passed:true,checks,consoleErrors:errors},null,2));
}catch(e){
  if(page)await page.screenshot({path:path.join(reports,'failure.png')}).catch(()=>{});
  console.error(e);throw e;
}finally{
  await app.evaluate(({app})=>app.exit(0)).catch(()=>{});
}
const restarted=await electron.launch({...(process.env.ACCOUNTOR_EXECUTABLE?{executablePath:process.env.ACCOUNTOR_EXECUTABLE,args:[]}:{args:[root]}),env:{...process.env,ACCOUNTOR_DATA_DIR:path.join(testRoot,'data')}});
try{
 const restored=await restarted.firstWindow();await expect(restored.getByRole('heading',{name:'账号工具研发',exact:true})).toBeVisible();
 await expect(restored.locator('html')).toHaveAttribute('data-theme','light');
 const restoredState=await restored.evaluate(()=>window.accountor.invoke('state:get'));
 expect(restoredState.settings.opacity).toBe(50);expect(Object.values(restoredState.drafts).some(d=>d.text.includes('本地草稿'))).toBe(true);
 await restored.getByRole('button',{name:'README.md',exact:true}).click();
 await expect(restored.getByText('磁盘文件已变化',{exact:true})).toBeVisible();
 const stored=JSON.parse(await fs.readFile(path.join(reports,'smoke.json'),'utf8'));stored.checks.push('restart restores workspace, layout, theme and conflict draft');await fs.writeFile(path.join(reports,'smoke.json'),JSON.stringify(stored,null,2));
 console.log('Restart persistence and draft recovery passed.');
}finally{await restarted.evaluate(({app})=>app.exit(0)).catch(()=>{});}
